-- Dashboard data sources only. Does not modify authentication, members, invitations or security settings.
CREATE TABLE public.crm_form_submissions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
 form_id uuid NOT NULL REFERENCES public.crm_forms(id) ON DELETE CASCADE,
 lead_id uuid REFERENCES public.leads(id) ON DELETE SET NULL,
 "values" jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof("values")='object'),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX slim_form_submissions_workspace_date ON public.crm_form_submissions(workspace_id,created_at DESC);
CREATE INDEX slim_form_submissions_form ON public.crm_form_submissions(form_id,created_at DESC);
CREATE TABLE public.tracking_sites (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
 name text NOT NULL CHECK(length(btrim(name)) BETWEEN 1 AND 160),
 domain text NOT NULL,
 pixel_token text NOT NULL DEFAULT encode(extensions.gen_random_bytes(24),'hex') UNIQUE,
 verified boolean NOT NULL DEFAULT false,
 last_event_at timestamptz,
 events_24h bigint NOT NULL DEFAULT 0,
 created_by uuid,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,domain)
);
CREATE TABLE public.tracking_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
 site_id uuid REFERENCES public.tracking_sites(id) ON DELETE CASCADE,
 event_id text,
 event_name text NOT NULL CHECK(length(event_name) BETWEEN 1 AND 120),
 session_id text,
 visitor_id text,
 lead_id uuid REFERENCES public.leads(id) ON DELETE SET NULL,
 source_class text NOT NULL DEFAULT 'cliente',
 page_path text,
 page_url text,
 referrer text,
 utm_source text,
 utm_medium text,
 utm_campaign text,
 utm_term text,
 utm_content text,
 fbclid text,
 gclid text,
 value numeric,
 currency text NOT NULL DEFAULT 'BRL',
 properties jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,site_id,event_id)
);
CREATE INDEX slim_tracking_events_workspace_date ON public.tracking_events(workspace_id,created_at DESC);
CREATE INDEX slim_tracking_events_site_date ON public.tracking_events(site_id,created_at DESC);
CREATE TABLE public.tracking_conversion_events (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
 event_row_id bigint REFERENCES public.tracking_events(id) ON DELETE CASCADE,
 conversion_id uuid,
 lead_id uuid REFERENCES public.leads(id) ON DELETE SET NULL,
 value numeric NOT NULL DEFAULT 0,
 currency text NOT NULL DEFAULT 'BRL',
 utm_source text,
 utm_campaign text,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,event_row_id,conversion_id)
);
CREATE INDEX slim_tracking_conversions_workspace_date ON public.tracking_conversion_events(workspace_id,created_at DESC);
CREATE FUNCTION private.slim_dashboard_source_references() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $body$
BEGIN
 IF TG_OP='UPDATE' AND NEW.workspace_id IS DISTINCT FROM OLD.workspace_id THEN RAISE EXCEPTION 'Empresa do registro não pode ser alterada.' USING ERRCODE='42501'; END IF;
 IF NEW.lead_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.leads l WHERE l.id=NEW.lead_id AND l.workspace_id=NEW.workspace_id) THEN RAISE EXCEPTION 'Cliente não pertence a esta empresa.' USING ERRCODE='42501'; END IF;
 IF TG_TABLE_NAME='crm_form_submissions' THEN
  IF NOT EXISTS(SELECT 1 FROM public.crm_forms f WHERE f.id=NEW.form_id AND f.workspace_id=NEW.workspace_id) THEN RAISE EXCEPTION 'Formulário não pertence a esta empresa.' USING ERRCODE='42501'; END IF;
 ELSIF TG_TABLE_NAME='tracking_events' THEN
  IF NEW.site_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.tracking_sites s WHERE s.id=NEW.site_id AND s.workspace_id=NEW.workspace_id) THEN RAISE EXCEPTION 'Site não pertence a esta empresa.' USING ERRCODE='42501'; END IF;
 ELSIF TG_TABLE_NAME='tracking_conversion_events' THEN
  IF NEW.event_row_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.tracking_events e WHERE e.id=NEW.event_row_id AND e.workspace_id=NEW.workspace_id) THEN RAISE EXCEPTION 'Evento não pertence a esta empresa.' USING ERRCODE='42501'; END IF;
 END IF;
 RETURN NEW;
END;$body$;
