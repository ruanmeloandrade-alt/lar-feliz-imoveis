import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { normalizeBrainTerm, validateBrainTitle, validateBrainUrl, validateBrainFile, isWorkspaceBrainPath, requireEditedRow } from '../src/lib/brain-editor.core.ts';
let passed=0;
const test=(name,fn)=>{fn();passed++;console.log('PASS '+name);};
test('term normalization',()=>assert.equal(normalizeBrainTerm('  NÃO GARANTIDO  '),'não garantido'));
test('empty term rejected',()=>assert.throws(()=>normalizeBrainTerm('  ')));
test('term length limit',()=>assert.throws(()=>normalizeBrainTerm('x'.repeat(121))));
test('maximum term accepted',()=>assert.equal(normalizeBrainTerm('x'.repeat(120)).length,120));
test('empty title rejected',()=>assert.throws(()=>validateBrainTitle(' ')));
test('trimmed title',()=>assert.equal(validateBrainTitle(' Promoção '),'Promoção'));
for(const link of ['javascript:alert(1)','data:text/html,test','ftp://example.com','https://user:pass@example.com','not-a-url']) test('reject unsafe URL '+link,()=>assert.throws(()=>validateBrainUrl(link)));
test('https URL',()=>assert.equal(validateBrainUrl(' https://example.com/a '),'https://example.com/a'));
test('accept PDF',()=>assert.equal(validateBrainFile({name:'guia.PDF',size:100}),'pdf'));
test('file limit',()=>assert.throws(()=>validateBrainFile({name:'guia.pdf',size:20*1024*1024+1})));
test('reject script',()=>assert.throws(()=>validateBrainFile({name:'guia.html',size:100})));
test('reject empty file',()=>assert.throws(()=>validateBrainFile({name:'guia.txt',size:0})));
test('private workspace path',()=>assert.equal(isWorkspaceBrainPath('empresa/a.pdf','empresa'),true));
test('other workspace blocked',()=>assert.equal(isWorkspaceBrainPath('outra/a.pdf','empresa'),false));
test('traversal blocked',()=>assert.equal(isWorkspaceBrainPath('empresa/../a.pdf','empresa'),false));
test('zero rows is not success',()=>assert.throws(()=>requireEditedRow([])));
test('one edited row',()=>assert.equal(requireEditedRow([{id:'1'}]).id,'1'));
const root = fileURLToPath(new URL('../',import.meta.url));
const component=fs.readFileSync(root+'src/components/crm/BrainSourceEditors.tsx','utf8');
const page=fs.readFileSync(root+'src/routes/crm.agente-ia.tsx','utf8');
test('both controls on actual page',()=>{assert.match(page,/<BrainSourceActions /);assert.match(page,/<BrainBlockedTermEditor /);});
test('source compare-and-swap',()=>{assert.match(component,/query\.eq\('updated_at', snapshot.updated_at\)/);assert.match(component,/\.eq\('workspace_id', workspaceId\)/);});
test('word compare-and-swap',()=>assert.match(component,/\.eq\('term', item.term\)/));
test('confirm rows before success',()=>assert.match(component,/requireEditedRow\(result.data\)/));
test('no privileged browser credential',()=>assert.doesNotMatch(component,/service_role|supabaseAdmin|client\.server|dangerouslySetInnerHTML/));
for(const name of ['src/components/crm/BrainSourceEditors.tsx','src/lib/brain-editor.core.ts','src/routes/crm.agente-ia.tsx']) test('TS syntax '+name,()=>{
 const result=ts.transpileModule(fs.readFileSync(root+name,'utf8'),{fileName:name,reportDiagnostics:true,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX}});
 assert.equal((result.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error).length,0);
});
console.log(`Saúde Slim brain editor: ${passed} checks passed.`);
